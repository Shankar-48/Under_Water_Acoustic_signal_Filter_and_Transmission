def _prep(x, n=8192):
    x = np.asarray(x, float)[:n]; x = x - x.mean()
    return x / np.max(np.abs(x))


def _metrics(clean, est):
    return {"snr_db": snr_db(clean, est), "mse": float(np.mean((clean - est) ** 2)),
            "corr": float(np.corrcoef(clean, est)[0, 1]) if np.std(est) > 0 else float("nan")}


def run_filters(x, fs, snr_in, seed):
    """Each filter ALONE on the noisy signal, and the complete pipeline."""
    y, _, sigma = add_gaussian_noise(x, snr_in, np.random.default_rng(seed))
    outs, times = {"Noisy (no filter)": y}, {"Noisy (no filter)": 0.0}
    for name, fn in (("Kalman only", lambda: kalman_filter(y, sigma ** 2)), ("LMS only", lambda: lms_filter(y)),
                     ("Wiener only", lambda: wiener_filter(y, sigma ** 2)),
                     ("Butterworth only", lambda: butterworth_lowpass(y, fs, auto_cutoff_hz(y, fs))),
                     ("Full pipeline", lambda: denoise_pipeline(y, sigma ** 2, fs)["Butterworth (final)"])):
        t0 = time.perf_counter(); outs[name] = fn(); times[name] = time.perf_counter() - t0
    return {k: {**_metrics(x, v), "time_s": times[k]} for k, v in outs.items()}


def exp_filters_vs_noise(seed=42, trials=3, snrs=(-5, 0, 5, 10, 15, 20), source="Biological"):
    x, fs = generate(source, 0); x = _prep(x)
    rows = []
    for s in snrs:
        for t in range(trials):
            for name, m in run_filters(x, fs, s, seed + t).items():
                rows.append({"data_mode": "SYNTHETIC", "source": source, "input_snr_db": s, "trial": t, "method": name, **m})
    df = pd.DataFrame(rows)
    base = df[df.method == "Noisy (no filter)"].set_index(["input_snr_db", "trial"])["snr_db"]
    df["snr_improvement_db"] = [r.snr_db - base[(r.input_snr_db, r.trial)] for r in df.itertuples()]
    return df


def exp_source_categories(seed=42, snr_in=5.0):
    rows = []
    for cat in GENERATORS:
        x, fs = generate(cat, 0); x = _prep(x, 8192)
        m = run_filters(x, fs, snr_in, seed)["Full pipeline"]
        base = run_filters(x, fs, snr_in, seed)["Noisy (no filter)"]["snr_db"]
        c = classify(*generate(cat, 0))
        rows.append({"data_mode": "SYNTHETIC", "category": cat, "fs_hz": fs, "input_snr_db": round(base, 2), "output_snr_db": round(m["snr_db"], 2),
                     "snr_improvement_db": round(m["snr_db"] - base, 2), "baseline_prediction": c["prediction"], "top_score": round(max(c["scores"].values()), 2)})
    return pd.DataFrame(rows)


