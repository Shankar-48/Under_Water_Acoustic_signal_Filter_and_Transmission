def exp_waveform_link(seed=42, distances=(500, 1500, 3000, 5000, 6500, 8000), n_packets=30, source_level=170.0):
    cfg = ModemConfig(); rows = []
    for name, kw in CONDITIONS.items():
        fx = ChannelEffects(**kw)
        for d in distances:
            rng = np.random.default_rng(seed + int(d))
            r = measure_per(d, source_level, fx, cfg, rng, n_packets)
            rows.append({"data_mode": "SIMULATED waveform channel", "condition": name, "distance_m": d, **r})
    return pd.DataFrame(rows)


def exp_model_vs_waveform(seed=42, distances=(4000, 5000, 6000, 7000), n_packets=40):
    """Link-budget model PER (Eb/N0 := SNR) vs PER measured with the waveform chain, same flat noise."""
    cfg = ModemConfig(); fx = ChannelEffects(noise_model="gaussian_white", white_psd_db=70.0); rows = []
    ch = ChannelConfig(source_level_db=170.0, carrier_khz=cfg.fc_hz / 1000, bit_rate_bps=cfg.bit_rate, noise_level_db=70.0 + 10 * np.log10(cfg.bit_rate),
                       packet_bits=32 + 8 + 128 + 16)
    from simulation.acoustic_channel import AcousticChannel
    ac = AcousticChannel(ch)
    for d in distances:
        rep = ac.link_report(d)
        m = measure_per(d, 170.0, fx, cfg, np.random.default_rng(seed + d), n_packets, payload_len=16)
        rows.append({"distance_m": d, "model_snr_db": round(rep["snr_db"], 2), "model_per": round(rep["per"], 4), "waveform_per": round(m["per"], 4),
                     "waveform_ber": round(m["ber"], 5), "packets": n_packets})
    return pd.DataFrame(rows)


def exp_relay_failure(seed=42, n=300):
    """PDR per explorer before/after relay failures. Batteries are refilled per packet so that only links and routing matter."""
    rows = []
    for phase in ("before failure", "RELAY-01 failed", "RELAY-01 and RELAY-02 failed"):
        env = Environment(seed=seed)
        if phase != "before failure": env.set_state("RELAY-01", "FAILED")
        if phase.startswith("RELAY-01 and"): env.set_state("RELAY-02", "FAILED")
        for src in env.ids("EXPLORER"):
            ok = unreach = 0; delays = []
            for _ in range(n):
                for nd in env.nodes.values(): nd.battery = 100.0       # isolate link/route behaviour from battery depletion
                tr = env.send_packet(src)
                ok += tr["delivered"]; unreach += tr["reason"].startswith("no route")
                if tr["delivered"]: delays.append(tr["t_end"] - tr["t_start"])
            rep = env.route_report(src)
            rows.append({"data_mode": "SIMULATED network", "phase": phase, "source": src, "route": " -> ".join(rep["primary"].path) if rep["reachable"] else "UNREACHABLE",
                         "hops": rep["primary"].hops if rep["reachable"] else 0, "pdr": round(ok / n, 4), "unreachable_packets": unreach,
                         "mean_delay_s": round(float(np.mean(delays)), 3) if delays else float("nan")})
    return pd.DataFrame(rows)


def exp_direct_vs_multihop(seed=42, n=2000, noise_levels=(105, 112, 118, 122)):
    rows = []
    for nl in noise_levels:
        env = Environment(ChannelConfig(noise_level_db=nl), seed=seed)
        for src in env.ids("EXPLORER"):
            for mode in ("direct_range_limited", "direct_ignore_range", "multihop"):
                r = env.simulate_delivery(src, n, mode)
                rows.append({"data_mode": "SIMULATED network", "noise_level_db": nl, "source": src, "scheme": mode, "hops": r["hops"], "pdr": round(r["pdr"], 4),
                             "mean_delay_s": round(r["mean_delay_s"], 3) if r["mean_delay_s"] == r["mean_delay_s"] else np.nan})
    return pd.DataFrame(rows)


def exp_ship_noise_routing(seed=42, steps=40, dt=15.0):
    """Link quality / route over time while ships move past (ship noise couples into receiver noise)."""
    env = Environment(seed=seed); rows = []
    for i in range(steps):
        rep = env.route_report("EXPLORER-01")
        rows.append({"data_mode": "SIMULATED network", "t_s": env.time, "route": " -> ".join(rep["primary"].path) if rep["reachable"] else "UNREACHABLE",
                     "min_link_snr_db": round(min(l["snr_db"] for l in rep["primary"].links), 2) if rep["reachable"] else np.nan,
                     "rx_noise_relay01_db": round(env.rx_noise_db("RELAY-01"), 2), "ambient_db": round(env.channel.noise_db(), 2)})
        env.step(dt)
    return pd.DataFrame(rows)


def exp_classification_demo(seed=0):
    """Pipeline demonstration on SYNTHETIC labelled data ONLY. Metrics describe the synthetic generators, not the ocean."""
    from classification.trained import train, MIN_RECORDINGS
    items = []
    for cat in GENERATORS:
        if cat == "Mixed": continue
        for i in range(MIN_RECORDINGS + 3):
            x, fs = generate(cat, 100 + i); items.append((x, fs, cat, f"{cat}_{i}"))
    clf, info = train(items, seed=seed, demo_label="SYNTHETIC DEMONSTRATION ONLY")
    rows = [{"class": k, **{m: round(v[m], 3) for m in ("precision", "recall", "f1-score")}, "support": int(v["support"])} for k, v in info["report"].items()
            if k in info["labels"]]
    return pd.DataFrame(rows), info


def run_extended(out=OUT, fast=True, seed=42, log=print):
    out = Path(out); (out / "figures").mkdir(parents=True, exist_ok=True)
    res = {}
    res["ext_filters_vs_noise"] = exp_filters_vs_noise(seed, trials=2 if fast else 5)
    res["ext_source_categories"] = exp_source_categories(seed)
    res["ext_waveform_link"] = exp_waveform_link(seed, n_packets=15 if fast else 40)
    res["ext_model_vs_waveform"] = exp_model_vs_waveform(seed, n_packets=25 if fast else 60)
    res["ext_relay_failure"] = exp_relay_failure(seed, n=100 if fast else 400)
    res["ext_direct_vs_multihop"] = exp_direct_vs_multihop(seed, n=500 if fast else 2000)
    res["ext_ship_noise_routing"] = exp_ship_noise_routing(seed)
    demo, info = exp_classification_demo()
    res["ext_classification_SYNTHETIC_DEMO"] = demo
    for k, df in res.items():
        df.to_csv(out / f"{k}.csv", index=False); log(f"wrote {k}.csv ({len(df)} rows)")
    try:
        make_figures(res, out / "figures")
    except Exception as e:                     # graphs are optional; CSVs are the primary output
        log(f"figures skipped: {e}")
    return res


def make_figures(res, figdir):
    import matplotlib; matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    f = res["ext_filters_vs_noise"]; g = f.groupby(["method", "input_snr_db"])["snr_improvement_db"].mean().unstack(0)
    ax = g.drop(columns="Noisy (no filter)").plot(marker="o", figsize=(7, 4)); ax.axhline(0, color="k", lw=.5)
    ax.set_ylabel("SNR improvement (dB)"); ax.set_xlabel("Input SNR (dB)"); ax.set_title("Filters alone vs full pipeline (SYNTHETIC whistle-like signal)"); plt.tight_layout(); plt.savefig(figdir / "filters_vs_noise.png", dpi=130); plt.close()
    w = res["ext_waveform_link"]; fig, ax = plt.subplots(figsize=(7.5, 4.2))
    for c, d in w.groupby("condition"): ax.plot(d.distance_m, d.pdr, marker="o", label=c)
    ax.set_xlabel("Distance (m)"); ax.set_ylabel("Packet delivery ratio"); ax.legend(fontsize=6); ax.set_title("Waveform-level BPSK link, SL=170 dB (SIMULATED channel)"); plt.tight_layout(); plt.savefig(figdir / "waveform_link_pdr.png", dpi=130); plt.close()
    r = res["ext_relay_failure"]; fig, ax = plt.subplots(figsize=(7, 4)); p = r.pivot(index="source", columns="phase", values="pdr"); p.plot.bar(ax=ax)
    ax.set_ylabel("Packet delivery ratio"); ax.set_title("Relay failure: PDR per explorer (SIMULATED network)"); plt.tight_layout(); plt.savefig(figdir / "relay_failure.png", dpi=130); plt.close()
    d = res["ext_direct_vs_multihop"]; fig, ax = plt.subplots(figsize=(7, 4)); q = d[d.source == "EXPLORER-01"].pivot(index="noise_level_db", columns="scheme", values="pdr"); q.plot(marker="o", ax=ax)
    ax.set_ylabel("PDR"); ax.set_title("Direct vs multi-hop, EXPLORER-01 (SIMULATED)"); plt.tight_layout(); plt.savefig(figdir / "direct_vs_multihop.png", dpi=130); plt.close()
    s = res["ext_ship_noise_routing"]; fig, ax = plt.subplots(figsize=(7, 3.6)); ax.plot(s.t_s, s.rx_noise_relay01_db, label="noise at RELAY-01 (ambient + ships)"); ax.axhline(s.ambient_db.iloc[0], ls="--", c="gray", label="ambient only")
    ax.set_xlabel("Simulated time (s)"); ax.set_ylabel("dB re 1 uPa (in-band)"); ax.legend(); ax.set_title("Moving ships raise receiver noise (assumed ship source levels)"); plt.tight_layout(); plt.savefig(figdir / "ship_noise.png", dpi=130); plt.close()
